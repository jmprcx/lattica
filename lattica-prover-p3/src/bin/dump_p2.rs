//! Dump the vetted Poseidon2-Goldilocks constants + known-answer vectors as Zig literals, so the
//! Zig `poseidon2.zig` can match the circuit byte-for-byte (C-03). Run: `cargo run --bin dump_p2`.

use lattica_prover_p3::joinsplit_air::{commit, merge, nullifier, recipient_of};
use lattica_prover_p3::poseidon2_air::native_permute;
use p3_field::{PrimeCharacteristicRing, PrimeField64};
use p3_goldilocks::{
    Goldilocks, GOLDILOCKS_POSEIDON2_RC_8_EXTERNAL_FINAL, GOLDILOCKS_POSEIDON2_RC_8_EXTERNAL_INITIAL,
    GOLDILOCKS_POSEIDON2_RC_8_INTERNAL, MATRIX_DIAG_8_GOLDILOCKS,
};

fn u(x: Goldilocks) -> u64 {
    x.as_canonical_u64()
}
fn g(x: u64) -> Goldilocks {
    Goldilocks::from_u64(x)
}

fn main() {
    println!("// generated by `cargo run --bin dump_p2` — vetted Poseidon2-Goldilocks constants");
    print!("pub const DIAG8 = [8]u64{{ ");
    for x in MATRIX_DIAG_8_GOLDILOCKS {
        print!("{}, ", u(x));
    }
    println!("}};");

    println!("pub const EXT_INIT = [4][8]u64{{");
    for row in GOLDILOCKS_POSEIDON2_RC_8_EXTERNAL_INITIAL {
        print!("    .{{ ");
        for x in row {
            print!("{}, ", u(x));
        }
        println!("}},");
    }
    println!("}};");

    println!("pub const EXT_FINAL = [4][8]u64{{");
    for row in GOLDILOCKS_POSEIDON2_RC_8_EXTERNAL_FINAL {
        print!("    .{{ ");
        for x in row {
            print!("{}, ", u(x));
        }
        println!("}},");
    }
    println!("}};");

    print!("pub const INTERNAL = [22]u64{{ ");
    for x in GOLDILOCKS_POSEIDON2_RC_8_INTERNAL {
        print!("{}, ", u(x));
    }
    println!("}};");

    // KATs (Zig comments): raw permutation + the domain-tagged hashes
    let perm = native_permute(core::array::from_fn(|i| g(i as u64)));
    println!("// KAT permute([0..8]) = {:?}", perm.map(u));
    let rcp = recipient_of(g(7));
    println!("// KAT recipient_of(7) = {:?}", rcp.map(u));
    println!("// KAT commit(rcp,1000,11,100) = {:?}", commit(rcp, g(1000), g(11), g(100)).map(u));
    println!("// KAT nullifier(7,11,9) = {:?}", nullifier(g(7), g(11), g(9)).map(u));
    let l = [g(1), g(2), g(3), g(4)];
    let r = [g(5), g(6), g(7), g(8)];
    println!("// KAT merge([1..4],[5..8]) = {:?}", merge(l, r).map(u));
}
